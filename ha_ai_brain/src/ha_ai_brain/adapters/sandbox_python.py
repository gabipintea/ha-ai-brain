"""Isolated Subprocess + AST-Validated Python Scientific Sandbox Adapter for the Computation Sub-Agent."""

from __future__ import annotations

import ast
import asyncio
import json
import sys
from typing import Any

from ha_ai_brain.ports.sandbox import ComputationSandboxPort


_SUBPROCESS_HARNESS = """
import json, math, statistics, sys

SAFE_BUILTINS = {
    "abs": abs, "all": all, "any": any, "bool": bool, "dict": dict,
    "enumerate": enumerate, "filter": filter, "float": float, "int": int,
    "isinstance": isinstance, "len": len, "list": list, "map": map,
    "max": max, "min": min, "pow": pow, "range": range, "round": round,
    "set": set, "sorted": sorted, "str": str, "sum": sum, "tuple": tuple, "zip": zip,
    "Exception": Exception, "ValueError": ValueError, "TypeError": TypeError,
}

payload = json.loads(sys.stdin.read())
code = payload["code"]
inputs = payload["inputs"]
results = {"signals": []}
namespace = {
    "__builtins__": SAFE_BUILTINS,
    "math": math,
    "statistics": statistics,
    "inputs": inputs,
    "results": results,
}
exec(compile(code, "<computation_subagent_sandbox>", "exec"), namespace, namespace)
out = namespace.get("results", results)
sys.stdout.write(json.dumps(out if isinstance(out, dict) else {"signals": []}))
"""


class PythonSandboxAdapter(ComputationSandboxPort):
    """
    Executes Python scientific/mathematical code generated by the Computation Sub-Agent
    inside an isolated `python -I` subprocess after AST validation (blocking imports and dunders).
    """

    @staticmethod
    def _validate_ast(code: str) -> str:
        tree = ast.parse(code, filename="<computation_subagent_sandbox>")
        filtered_body = []
        for stmt in tree.body:
            if isinstance(stmt, ast.Import) and all(alias.name in ("math", "statistics") for alias in stmt.names):
                continue
            filtered_body.append(stmt)
        tree.body = filtered_body
        for node in ast.walk(tree):
            if isinstance(node, (ast.Import, ast.ImportFrom)):
                raise ValueError("Import statements are forbidden inside the computation sandbox; use `math` and `statistics`.")
            if isinstance(node, ast.Attribute) and node.attr.startswith("__"):
                raise ValueError(f"Access to dunder attribute '{node.attr}' is forbidden in sandbox.")
            if isinstance(node, ast.Name) and node.id.startswith("__"):
                raise ValueError(f"Access to dunder identifier '{node.id}' is forbidden in sandbox.")
        return ast.unparse(tree)

    async def execute_python(
        self,
        code: str,
        input_variables: dict[str, Any],
        timeout_seconds: float = 5.0,
    ) -> dict[str, Any]:
        """Validate AST and run the Python snippet in an isolated subprocess with `inputs`."""
        proc = None
        try:
            sanitized_code = self._validate_ast(code)
            proc = await asyncio.create_subprocess_exec(
                sys.executable,
                "-I",
                "-c",
                _SUBPROCESS_HARNESS,
                stdin=asyncio.subprocess.PIPE,
                stdout=asyncio.subprocess.PIPE,
                stderr=asyncio.subprocess.PIPE,
            )
            stdin_bytes = json.dumps({"code": sanitized_code, "inputs": input_variables}).encode("utf-8")
            stdout_bytes, stderr_bytes = await asyncio.wait_for(
                proc.communicate(input=stdin_bytes),
                timeout=timeout_seconds,
            )
            if proc.returncode != 0:
                return {"signals": [], "error": stderr_bytes.decode("utf-8", errors="replace").strip()}
            return json.loads(stdout_bytes.decode("utf-8"))
        except asyncio.TimeoutError:
            if proc is not None:
                try:
                    proc.kill()
                    await proc.wait()
                except Exception:
                    pass
            return {"signals": [], "error": f"Computation timed out after {timeout_seconds}s"}
        except Exception as exc:
            return {"signals": [], "error": str(exc)}
